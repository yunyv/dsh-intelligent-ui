/** Build the isolated MathJax Worker; never run the host tsdown configuration. */
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { Script } from 'node:vm'
import { build } from 'tsdown'
import ts from 'typescript'

const root = new URL('../', import.meta.url)
const destination = new URL('src/client/dil/math/generated/worker-source.ts', root)
for (const name of ['@mathjax/src', '@mathjax/mathjax-newcm-font']) {
	const pkg = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, root), 'utf8'))
	if (pkg.version !== '4.1.3') throw new Error(`Offline math requires ${name}@4.1.3, found ${pkg.version}`)
}

const bundles = await build({
	config: false,
	entry: { 'math-worker': fileURLToPath(new URL('src/client/dil/math/worker-entry.ts', root)) },
	root: fileURLToPath(root),
	outDir: fileURLToPath(new URL('src/client/dil/math/generated/', root)),
	platform: 'browser',
	target: 'es2022',
	format: 'iife',
	write: false,
	clean: false,
	dts: false,
	sourcemap: false,
	minify: true,
	deps: {
		alwaysBundle: [/^@mathjax\//],
		onlyBundle: [/^@mathjax\//],
		onlyImport: []
	},
	inputOptions: { onwarn(warning) { throw new Error(`Math Worker build warning: ${warning.message}`) } }
})

try {
	const chunks = bundles.flatMap((bundle) => bundle.chunks)
	if (chunks.length !== 1 || chunks[0].type !== 'chunk' || !chunks[0].isEntry) {
		throw new Error('Math Worker must be exactly one entry chunk with no assets')
	}
	const chunk = chunks[0]
	if (chunk.imports.length || chunk.dynamicImports.length) throw new Error('Math Worker has external or dynamic imports')
	const notice = [
		'/*! Offline MathJax 4.1.3 / MathJax-NewCM 4.1.3.',
		' * MathJax core code (Apache-2.0); retained source notices:',
		' * Copyright (c) 2009-2026 The MathJax Consortium',
		' * Copyright (c) 2017-2026 The MathJax Consortium',
		' * Copyright (c) 2018-2026 The MathJax Consortium',
		' * Copyright (c) 2019-2026 The MathJax Consortium',
		' * Copyright (c) 2020-2026 The MathJax Consortium',
		' * Copyright (c) 2021-2026 The MathJax Consortium',
		' * Copyright (c) 2022-2026 The MathJax Consortium',
		' * Copyright (c) 2023-2026 The MathJax Consortium',
		' * Copyright (c) 2024-2026 The MathJax Consortium',
		' * Copyright (c) 2026 The MathJax Consortium',
		' * Font attribution includes (C) 2019-2021 Antonis Tsolomitis and',
		' * Copyright (c) 2024 MathJax, Inc.; retain GUST/LPPL font notices.',
		' * Bundled data and local adaptations: assets/math/THIRD_PARTY_NOTICES.md.',
		' * Licence texts: assets/math/{APACHE-2.0,GUST-FONT-LICENSE,LPPL-1.3c}.txt.',
		' */',
		''
	].join('\n')
	const source = notice + chunk.code
	new Script(source, { filename: 'math-worker.js' })
	const parsed = ts.createSourceFile('math-worker.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
	function check(node) {
		if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)
			|| (ts.isCallExpression(node) && (node.expression.kind === ts.SyntaxKind.ImportKeyword
				|| (ts.isIdentifier(node.expression) && node.expression.text === 'require')))) {
			throw new Error('Math Worker contains a module-loading expression')
		}
		ts.forEachChild(node, check)
	}
	check(parsed)
	const hash = createHash('sha256').update(source).digest('hex')
	const generated = [
		'/**',
		' * GENERATED by scripts/build-math-worker.mjs — do not edit by hand.',
		' * Source: src/client/dil/math/worker-entry.ts, engine.ts, newcm.ts, protocol.ts.',
		' * MathJax 4.1.3 + NewCM 4.1.3; one offline IIFE for a dedicated Blob Worker.',
		` * Worker source SHA-256: ${hash}`,
		' */',
		`export const MATH_WORKER_SOURCE: string = ${JSON.stringify(source).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')}`,
		''
	].join('\n')
	await mkdir(new URL('./', destination), { recursive: true })
	await writeFile(destination, generated)
	console.log(`Generated math Worker: ${Buffer.byteLength(source)} bytes; SHA-256 ${hash}`)
} finally {
	for (const bundle of bundles) await bundle[Symbol.asyncDispose]()
}
